class Solution {
    public long countCommas(long n) {

        if (n < 1000) {
            return 0;
        }

        if (n < 1_000_000) {
            return n - 1000 + 1;
        }

        if (n < 1_000_000_000L) {
            return (1_000_000L - 1000)
                    + (n - 1_000_000L + 1) * 2;
        }

        if (n < 1_000_000_000_000L) {
            return (1_000_000L - 1000)
                    + (1_000_000_000L - 1_000_000L) * 2
                    + (n - 1_000_000_000L + 1) * 3;
        }

        if (n < 1_000_000_000_000_000L) {
            return (1_000_000L - 1000)
                    + (1_000_000_000L - 1_000_000L) * 2
                    + (1_000_000_000_000L - 1_000_000_000L) * 3
                    + (n - 1_000_000_000_000L + 1) * 4;
        }

        // 1,000,000,000,000,000 itself has 5 commas
        return (1_000_000L - 1000)
                + (1_000_000_000L - 1_000_000L) * 2
                + (1_000_000_000_000L - 1_000_000_000L) * 3
                + (1_000_000_000_000_000L - 1_000_000_000_000L) * 4
                + (n - 1_000_000_000_000_000L + 1) * 5;
    }
}